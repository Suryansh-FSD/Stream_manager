"""
Deterministic Synthetic Benchmark Dataset Generator for Spotify Trends.
Generates realistic but explicitly synthetic music track records for development,
benchmarking, and testing of the data engineering pipeline and analytics engine.

DISCLAIMER: All records generated by this module are purely synthetic benchmarks.
They do NOT represent official Spotify metrics, streams, or proprietary data.
"""
import argparse
import random
from pathlib import Path
from typing import List, Dict, Any
import pandas as pd
import numpy as np

from pipeline.config import RAW_DATA_DIR

RANDOM_SEED = 42

SYNTHETIC_ARTISTS = [
    "Aura Echo", "Solaris", "Luna Bay", "The Midnight Pulse", "Kavinsky Sound",
    "Velvet Groove", "Neon Vanguard", "Starlight Symphony", "Prism Drift",
    "Cybernetic Ensemble", "Echo Valley", "Quantum Beats", "Hyperion",
    "Astral Projection", "The Soundwave Collective", "AC/DC", "Daft Horizon"
]

SYNTHETIC_GENRES = [
    "Synthwave", "Indie Pop", "Electronic", "Lo-Fi Beats", "Alternative Rock",
    "Deep House", "Ambient", "R&B", "Future Bass", "Dream Pop"
]

SYNTHETIC_WORDS_1 = [
    "Midnight", "Neon", "Electric", "Solar", "Velvet", "Silent", "Lost", "Golden",
    "Cosmic", "Ocean", "Infinite", "Ephemeral", "Digital", "Radiant", "Fading"
]

SYNTHETIC_WORDS_2 = [
    "Echoes", "Horizons", "Drift", "Dreams", "Pulse", "Shadows", "Waves", "Memories",
    "Vibrations", "Nights", "Lights", "Reflections", "Symphony", "Serenade", "Gravity"
]


def generate_synthetic_benchmark_dataset(
    record_count: int = 250, 
    seed: int = RANDOM_SEED,
    include_duplicates: bool = True
) -> pd.DataFrame:
    """
    Generates a deterministic synthetic benchmark dataset with realistic distributions,
    multi-artist collaborations, varied date precisions, and controlled edge cases.
    """
    random.seed(seed)
    np.random.seed(seed)

    records: List[Dict[str, Any]] = []

    for i in range(record_count):
        # Deterministic title
        w1 = random.choice(SYNTHETIC_WORDS_1)
        w2 = random.choice(SYNTHETIC_WORDS_2)
        track_name = f"{w1} {w2}" if random.random() > 0.15 else f"{w1} {w2} (Part {random.randint(1, 3)})"

        # Deterministic artist with collaborations (feat., &, or comma)
        primary_artist = random.choice(SYNTHETIC_ARTISTS)
        collab_roll = random.random()
        if collab_roll < 0.20:
            secondary = random.choice([a for a in SYNTHETIC_ARTISTS if a != primary_artist])
            artist_str = f"{primary_artist} feat. {secondary}"
        elif collab_roll < 0.35:
            secondary = random.choice([a for a in SYNTHETIC_ARTISTS if a != primary_artist])
            artist_str = f"{primary_artist} & {secondary}"
        elif collab_roll < 0.45:
            secondary = random.choice([a for a in SYNTHETIC_ARTISTS if a != primary_artist])
            tertiary = random.choice([a for a in SYNTHETIC_ARTISTS if a not in [primary_artist, secondary]])
            artist_str = f"{primary_artist}, {secondary}, {tertiary}"
        else:
            artist_str = primary_artist

        # Album title
        album_name = f"{w1} LP" if random.random() > 0.4 else f"{track_name} (Single)"

        # Release date precision variation
        year = random.randint(2010, 2024)
        month = random.randint(1, 12)
        day = random.randint(1, 28)

        date_roll = random.random()
        if date_roll < 0.70:
            # Full YYYY-MM-DD
            rel_date = f"{year:04d}-{month:02d}-{day:02d}"
        elif date_roll < 0.85:
            # YYYY-MM
            rel_date = f"{year:04d}-{month:02d}"
        else:
            # YYYY
            rel_date = f"{year:04d}"

        # Popularity score (0 - 100)
        popularity = int(np.clip(np.random.normal(loc=65, scale=18), 0, 100))

        # Synthetic streams (deciles from 50k to 1.5B, distinctly separated from popularity)
        # Power law distribution typical of music streaming
        streams = int(np.random.pareto(a=1.8) * 1_500_000 + 75_000)

        # Duration: 120s to 320s
        duration_ms = int(random.gauss(210_000, 35_000))
        duration_ms = max(60_000, min(600_000, duration_ms))

        # Explicit flag
        explicit = random.random() < 0.12

        # Genre
        genre = random.choice(SYNTHETIC_GENRES)

        # Audio features (standard normalized 0.0 - 1.0 distributions)
        danceability = round(float(np.clip(np.random.beta(a=5, b=3), 0.05, 0.98)), 3)
        energy = round(float(np.clip(np.random.beta(a=4, b=3), 0.05, 0.99)), 3)
        key = random.randint(0, 11)
        loudness = round(float(np.clip(np.random.normal(loc=-7.5, scale=3.0), -45.0, -1.0)), 2)
        mode = 1 if random.random() > 0.35 else 0
        speechiness = round(float(np.clip(np.random.exponential(scale=0.08), 0.02, 0.70)), 3)
        acousticness = round(float(np.clip(np.random.beta(a=2, b=5), 0.001, 0.95)), 3)
        instrumentalness = round(float(np.clip(np.random.exponential(scale=0.15), 0.0, 0.95)), 3)
        liveness = round(float(np.clip(np.random.exponential(scale=0.12), 0.03, 0.85)), 3)
        valence = round(float(np.clip(np.random.beta(a=3, b=3), 0.05, 0.98)), 3)
        tempo = round(float(np.clip(np.random.normal(loc=122.0, scale=24.0), 60.0, 210.0)), 1)
        time_signature = 4 if random.random() > 0.1 else 3

        track_id = f"synth_track_{i+1:04d}"

        records.append({
            "track_id": track_id,
            "track_name": track_name,
            "artist_name": artist_str,
            "album_name": album_name,
            "release_date": rel_date,
            "popularity": popularity,
            "streams": streams,
            "duration_ms": duration_ms,
            "explicit": explicit,
            "genre": genre,
            "danceability": danceability,
            "energy": energy,
            "key": key,
            "loudness": loudness,
            "mode": mode,
            "speechiness": speechiness,
            "acousticness": acousticness,
            "instrumentalness": instrumentalness,
            "liveness": liveness,
            "valence": valence,
            "tempo": tempo,
            "time_signature": time_signature,
            "is_synthetic_benchmark": True
        })

    # Controlled duplicate insertions for testing cleaner deduplication
    if include_duplicates and len(records) >= 5:
        num_dups = min(5, max(1, len(records) // 10))
        for dup_idx in range(num_dups):
            source_idx = (dup_idx * 7 + 2) % len(records)
            dup_record = dict(records[source_idx])
            dup_record["track_id"] = f"{dup_record['track_id']}_dup_{dup_idx}"
            dup_record["streams"] = int(dup_record["streams"] * 0.9)
            records.append(dup_record)

    df = pd.DataFrame(records)
    return df


def main():
    parser = argparse.ArgumentParser(description="Generate synthetic benchmark Spotify dataset.")
    parser.add_argument(
        "--output", 
        type=str, 
        default=str(RAW_DATA_DIR / "benchmark_spotify.csv"),
        help="Target output CSV filepath."
    )
    parser.add_argument(
        "--count", 
        type=int, 
        default=300, 
        help="Number of synthetic records to generate."
    )
    parser.add_argument(
        "--seed", 
        type=int, 
        default=RANDOM_SEED, 
        help="Random seed for reproducibility."
    )
    args = parser.parse_args()

    out_path = Path(args.output)
    out_path.parent.mkdir(parents=True, exist_ok=True)

    print(f"Generating {args.count} synthetic benchmark tracks (seed={args.seed})...")
    df = generate_synthetic_benchmark_dataset(record_count=args.count, seed=args.seed)
    df.to_csv(out_path, index=False)
    print(f"Successfully generated {len(df)} records (including controlled duplicates).")
    print(f"Saved synthetic benchmark to: {out_path.resolve()}")


if __name__ == "__main__":
    main()
